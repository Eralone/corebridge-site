'use client';

import { useEffect, useState } from 'react';
import Link from 'next/link';
import { getPlans } from '@/lib/api/lk';
import type { Plan } from '@/lib/contracts/lk';

/**
 * Сценарии n8n — публичная страница. Перенос design-source/n8n.html.
 *
 * ⚠️ Главное отличие: **в макете это был экран внутри кабинета** (обёртка `.app`
 * с сайдбаром и топбаром) с замком «разблокируется на тарифе». У нас кабинетный
 * экран — `/workflows`, а `/n8n` по карте маршрутов публичный: сюда приходят
 * из поиска и с лендинга, ещё не будучи клиентом. Поэтому:
 *
 * · **замок и оверлей убраны.** Человеку, который только знакомится с продуктом,
 *   нужно понять, что это, а не увидеть запрет;
 * · **вкладки убраны.** Три вкладки в макете («Шаблоны», «Редактор», «Как это
 *   работает») прятали половину объяснения за клик — на странице, вся задача
 *   которой объяснить, это лишний барьер. Содержимое идёт одним текстом;
 * · **«12 готовых сценариев» и «после перехода на Энтерпрайз» убраны.** Макет
 *   противоречил сам себе: баннер обещал «Профессионал», текст ниже —
 *   «Энтерпрайз». Тариф берём из каталога по признаку `features.n8n_ui`,
 *   количество сценариев не называем: каталог живой и меняется;
 * · список сценариев — примеры того, что уже опубликовано на сервере, без счёта.
 */
export function N8nBody() {
  const [plans, setPlans] = useState<Plan[] | null>(null);

  useEffect(() => {
    getPlans()
      .then((r) => setPlans(r.plans))
      .catch(() => setPlans([]));
  }, []);

  /** Младший тариф, где есть свой интерфейс n8n. Название — из каталога */
  const withUi = plans?.filter((p) => p.features.n8n_ui && !p.is_custom_price) ?? [];
  const planTitle = withUi[0]?.title;

  return (
    <div className="n8n-wrap">
      <div className="p-crumbs">
        <Link href="/">Главная</Link> / Сценарии n8n
      </div>

      <div className="lock-banner">
        <div className="icn">
          <svg width="32" height="32" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8">
            <circle cx="6" cy="6" r="2.5" />
            <circle cx="18" cy="18" r="2.5" />
            <path d="M8.5 6H13a4 4 0 0 1 4 4v5" />
            <path d="M6 8.5V14a4 4 0 0 0 4 4h5" />
          </svg>
        </div>
        <div>
          {/* ⚠️ был <h2>, и на странице не оказывалось ни одного <h1>: в эталоне
              баннер верстался вторым уровнем. Для поиска и скринридера это
              страница без названия. Вид не меняется — размер задан классом */}
          <h1>Свои правила поверх готовых интеграций</h1>
          <p>
            Когда стандартного обмена недостаточно: «если заказ оплачен и старше двух часов —
            отправить в Telegram с пометкой». Готовые сценарии работают на всех тарифах,
            а собственный редактор n8n внутри кабинета
            {planTitle ? ` — начиная с тарифа «${planTitle}»` : ' — на старших тарифах'}.
          </p>
        </div>
        <Link href="/pricing" className="btn btn-primary btn-lg">
          Посмотреть тарифы
        </Link>
      </div>

      <h3>Зачем это нужно</h3>
      <p>
        Стандартные интеграции в .epf покрывают типовые случаи: получить заказы, отправить
        остатки, выгрузить цены. Но у бизнеса почти всегда есть свои правила: «заказы из Москвы
        — на отдельный склад», «товар с маркировкой — уведомить кладовщика», «предоплата меньше
        50 % — не отгружать».
      </p>
      <p>
        Сценарий собирается из блоков: что запускает (событие), при каком условии, что сделать
        и куда отправить результат. Программировать не нужно — блоки соединяются мышью.
      </p>

      <h3>Как выглядит сценарий</h3>
      <p>
        Простейший пример: новый заказ с Ozon → проверить оплату → создать документ в 1С →
        сообщить в Telegram.
      </p>
      <div className="canvas">
        <div className="nodes">
          <div className="nd trg">Новый заказ Ozon</div>
          <div className="ln" />
          <div className="nd act">Проверить оплату</div>
          <div className="ln" />
          <div className="nd act">Создать в 1С</div>
          <div className="ln" />
          <div className="nd out">Telegram</div>
        </div>
      </div>

      <h3>Готовые сценарии</h3>
      <p>
        Их не нужно собирать с нуля — часть уже опубликована и включается одной кнопкой
        в кабинете. Каждый можно изменить под себя.
      </p>
      <div className="tpl-grid">
        {EXAMPLES.map((t) => (
          <article className="tpl" key={t.title}>
            <div className="ic">
              <svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
                {t.icon}
              </svg>
            </div>
            <h4>{t.title}</h4>
            <p>{t.text}</p>
            <div className="tags">
              {t.tags.map((g) => (
                <span className="tag" key={g}>
                  {g}
                </span>
              ))}
            </div>
          </article>
        ))}
      </div>
      <p className="text-muted" style={{ fontSize: 13, marginTop: 16 }}>
        Полный список доступен в кабинете — он пополняется, поэтому здесь только примеры.
      </p>

      <h3>Что входит</h3>
      <ul>
        <li>Готовые сценарии, которые включаются одной кнопкой</li>
        <li>Визуальный редактор: блоки соединяются мышью</li>
        <li>История запусков — видно, что и когда не сработало, и почему</li>
        <li>Запуск по событию из 1С или по расписанию</li>
        <li>Лимит запусков в месяц зависит от тарифа</li>
      </ul>

      <div className="row gap-12" style={{ marginTop: 28, flexWrap: 'wrap' }}>
        <Link href="/register" className="btn btn-primary btn-lg">
          Попробовать бесплатно
        </Link>
        <Link href="/docs" className="btn btn-outline btn-lg">
          Документация
        </Link>
      </div>
    </div>
  );
}

