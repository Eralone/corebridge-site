function apply(name, html, rules) {
  let out = html;
  const log = [];
  for (const r of rules) {
    const found = [...out.matchAll(new RegExp(r.from, r.from.flags.includes('g') ? r.from.flags : r.from.flags + 'g'))];
    if (r.count !== undefined && found.length !== r.count) {
      throw new Error(
        `${name}: правило «${r.why.slice(0, 60)}…» ожидало ${r.count} совпадений, нашло ${found.length}. ` +
          'Эталон изменился — правку надо перепроверить.',
      );
    }
    if (found.length === 0 && r.count === undefined) continue;
    out = out.replace(r.from, r.to);
    log.push(`  ${found.length}× ${r.why}`);
  }
  return { out, log };
}

const PAGES = {
  oferta: [...RULES.common, ...OFERTA, PHONE_OUT],
  privacy: [...RULES.common, ...RULES.privacy],
  terms: [...RULES.common, ...RULES.terms, ...TERMS_TABLE, PHONE_OUT],
};

mkdirSync(OUT, { recursive: true });

for (const [name, rules] of Object.entries(PAGES)) {
  const src = readFileSync(join(ROOT, 'design-source', `${name}.html`), 'utf8');
  const m = src.match(/<main class="legal-shell">([\s\S]*?)<\/main>/);
  if (!m) throw new Error(`${name}: не нашёл <main class="legal-shell">`);

  const { out, log } = apply(name, m[1], rules);
  console.log(`${name}.html → ${out.length} байт`);
  for (const line of log) console.log(line);

  const left = out.match(/Нидерланд|privacy@|support@|\.html"/g);
  if (left) throw new Error(`${name}: осталось непоправленным — ${[...new Set(left)].join(', ')}`);

  if (!check) writeFileSync(join(OUT, `${name}.html`), out.trim() + '\n', 'utf8');
}

console.log(check ? '\nПроверка пройдена, файлы не перезаписаны.' : `\nЗаписано в ${OUT}`);
