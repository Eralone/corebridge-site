/**
 * «Вход держится только в одном окне и недолго» — почему и что тут делается.
 *
 * ── Что происходит ───────────────────────────────────────────────────────────
 * Cookie `lk_session` сервер ставит с `SameSite=Strict`. Такую cookie браузер
 * **не отправляет** в запросе, рождённом переходом с чужого сайта: из письма,
 * из мессенджера, из поисковой выдачи, с oauth.yandex.ru. Сама cookie при этом
 * жива и лежит в браузере — не уходит только в этом одном запросе.
 *
 * Дальше происходит обидное: guard видит запрос без cookie, уводит на
 * `/login?next=…`, и человек уже стоит на форме входа. Обновление страницы
 * (F5) ничего не чинит — обновляется-то форма входа, а не закрытая страница,
 * куда он шёл. Со стороны выглядит как «сессия отвалилась».
 *
 * Проверено на живом сайте при одной и той же живой сессии:
 *
 *   адресная строка или закладка                → кабинет     ✓
 *   ссылка с чужого сайта прямо в кабинет       → форма входа ✗
 *     обновить эту страницу (F5)                → форма входа ✗
 *     перейти в кабинет уже изнутри сайта       → кабинет     ✓
 *
 * ── Почему это можно починить здесь ──────────────────────────────────────────
 * Ограничение `Strict` касается переходов, но **не** обычных запросов со
 * страницы: `fetch` к своему же серверу считается своим, и cookie в нём уходит.
 * Проверено там же: со страницы `/login`, куда только что выкинуло,
 * `GET /lk/auth/session` отвечает `200` с настоящим `user_id`.
 *
 * Поэтому не гадаем, а спрашиваем сервер напрямую. Ответ достоверный: `200` —
 * сессия действительно жива, и человека надо вернуть туда, куда он шёл.
 *
 * ⚠️ ВРЕМЕННО. Настоящее лечение — `sameSite: 'lax'` на сервере
 * (Documents/prompts/backend_S18_auth_cookie_and_mail.md): `Lax` отправляет
 * cookie при обычных переходах и по-прежнему не отправляет при межсайтовых
 * POST, то есть защита от CSRF остаётся. После этой правки модуль удалить.
 */

import { api } from '@/lib/api/client';

/** Одно возвращение за вкладку — страховка от петли, см. ниже. */
const ONCE_KEY = 'cb_session_recovered';

/** Ответ сервера, чтобы не спрашивать его на каждой публичной странице. */
const CACHE_KEY = 'cb_signed_in';

/** Жива ли сессия на самом деле. Ошибку наружу не пускаем: нет — значит нет. */
export async function hasLiveSession(): Promise<boolean> {
  try {
    await api<{ user_id: string }>('/lk/auth/session');
    return true;
  } catch {
    return false;
  }
}

/**
 * Можно ли ещё раз вернуть человека внутрь.
 *
 * ⚠️ Ровно один раз за вкладку, и в этом весь смысл. Guard разворачивает
 * на `/login` не только из-за потерянной cookie: заблокированному тенанту
 * он тоже откажет — а сессия при этом жива и `/lk/auth/session` отвечает `200`.
 * Без ограничения получилась бы петля «форма входа → кабинет → форма входа».
 */
export function claimRecovery(): boolean {
  try {
    if (sessionStorage.getItem(ONCE_KEY)) return false;
    sessionStorage.setItem(ONCE_KEY, '1');
    return true;
  } catch {
    // приватный режим может запрещать запись — тогда просто без восстановления
    return false;
  }
}

/**
 * Тот же ответ, но для шапки публичных страниц: вошедшему она показывает
 * «Личный кабинет» вместо «Войти».
 *
 * Ответ помним на вкладку — иначе к `lk-api` уходил бы лишний запрос с каждой
 * открытой страницы лендинга, включая обход поисковых роботов. Память
 * сбрасывается входом и выходом, поэтому устареть ей негде.
 */
export async function isSignedIn(): Promise<boolean> {
  try {
    const cached = sessionStorage.getItem(CACHE_KEY);
    if (cached !== null) return cached === '1';
  } catch {
    // без sessionStorage просто спросим сервер
  }
  const live = await hasLiveSession();
  try {
    sessionStorage.setItem(CACHE_KEY, live ? '1' : '0');
  } catch {
    /* не смогли запомнить — не беда */
  }
  return live;
}

/** Зовём при входе и выходе: состояние изменилось, помнить старое нельзя. */
export function forgetSessionState(): void {
  try {
    sessionStorage.removeItem(CACHE_KEY);
    sessionStorage.removeItem(ONCE_KEY);
  } catch {
    /* нечего забывать */
  }
}
