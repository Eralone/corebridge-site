/**
 * Знает ли браузер, что человек уже вошёл, — для шапки публичных страниц.
 *
 * ── Зачем это отдельно ───────────────────────────────────────────────────────
 * В эталоне шапка только гостевая: «Войти» и «Попробовать бесплатно»
 * показывались всем, включая вошедшего, и пути обратно в кабинет с лендинга
 * не было вовсе. Cookie сессии `HttpOnly`, из разметки её не прочитать,
 * а публичные страницы отдаются статикой — читать cookie на сервере значит
 * сделать их динамическими. Поэтому спрашиваем сервер из браузера.
 *
 * ── Почему ответ помним ──────────────────────────────────────────────────────
 * Иначе к `lk-api` уходил бы запрос с каждой открытой страницы лендинга,
 * включая обход поисковых роботов. Память живёт во вкладке и сбрасывается
 * входом и выходом (`forgetSessionState`), поэтому устареть ей негде.
 *
 * ── Чего здесь больше нет ────────────────────────────────────────────────────
 * До 2026-07-31 тут же лежало восстановление сессии: cookie стояла с
 * `SameSite=Strict` и не уходила в переходе с чужого сайта — из письма,
 * из мессенджера, с oauth.yandex.ru, — из-за чего вошедшего разворачивало
 * на форму входа, а F5 не помогал (обновлялась уже форма входа). Форма входа
 * спрашивала сервер и возвращала человека туда, куда он шёл.
 *
 * Сервер перевёл cookie на `sameSite: 'lax'` (пакет S18), обход снят: переход
 * с чужого сайта ведёт прямо в кабинет, guard не вмешивается — проверено.
 */

import { api } from '@/lib/api/client';

/** Ответ сервера, чтобы не спрашивать его на каждой публичной странице. */
const CACHE_KEY = 'cb_signed_in';

/** Жива ли сессия. Ошибку наружу не пускаем: нет ответа — значит не вошёл. */
async function hasLiveSession(): Promise<boolean> {
  try {
    await api<{ user_id: string }>('/lk/auth/session');
    return true;
  } catch {
    return false;
  }
}

export async function isSignedIn(): Promise<boolean> {
  try {
    const cached = sessionStorage.getItem(CACHE_KEY);
    if (cached !== null) return cached === '1';
  } catch {
    // без sessionStorage просто спросим сервер
  }
  const live = await hasLiveSession();
  try {
    sessionStorage.setItem(CACHE_KEY, live ? '1' : '0');
  } catch {
    /* не смогли запомнить — не беда */
  }
  return live;
}

/** Зовём при входе и выходе: состояние изменилось, помнить старое нельзя. */
export function forgetSessionState(): void {
  try {
    sessionStorage.removeItem(CACHE_KEY);
  } catch {
    /* нечего забывать */
  }
}
