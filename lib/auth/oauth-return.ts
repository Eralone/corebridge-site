/**
 * Обход того, что вход через Яндекс ID возвращает человека на форму входа.
 *
 * ── Что происходит ───────────────────────────────────────────────────────────
 * Cookie `lk_session` сервер ставит с `SameSite=Strict`. Браузер такую cookie
 * **не отправляет** в запросе, который возник из перехода с чужого сайта, —
 * а возврат из Яндекса именно такой:
 *
 *   oauth.yandex.ru → /lk/auth/yandex/callback (302) → /dashboard
 *
 * Cookie при этом сохраняется, но в запросе `/dashboard` её нет. Guard видит
 * «не авторизован» и уводит на `/login?next=/dashboard`. Со стороны выглядит
 * так, будто аккаунт не создался, — хотя он создан и сессия жива.
 * Проверено вживую: переход на закрытую страницу со стороннего origin при
 * живой сессии даёт `/login?next=…`, а точно такой же переход внутри сайта — нет.
 *
 * ── Почему это чинится здесь ─────────────────────────────────────────────────
 * Достаточно **одного** перехода внутри сайта: он уже считается своим, cookie
 * уходит, guard пускает. Мы этот переход и делаем — ровно один раз и только
 * если человек действительно уходил в Яндекс.
 *
 * ⚠️ ВРЕМЕННО. Настоящее лечение — `sameSite: 'lax'` на сервере
 * (Documents/prompts/backend_S18_auth_cookie_and_mail.md). После него сюда
 * попадать перестанут, и модуль можно снять.
 *
 * Метку намеренно храним в sessionStorage, а не в cookie: она переживает
 * уход на oauth.yandex.ru и обратно, живёт только во вкладке и сама исчезает.
 */

const KEY = 'cb_oauth_started_at';

/** Не старше двух минут: столько занимает подтверждение в Яндексе с запасом. */
const MAX_AGE_MS = 120_000;

/** Отмечаем, что уходим на внешнего провайдера. Зовём перед самим переходом. */
export function markOAuthStart(): void {
  try {
    sessionStorage.setItem(KEY, String(Date.now()));
  } catch {
    // приватный режим может запрещать запись — тогда просто без обхода
  }
}

/**
 * Мы вернулись от провайдера и оказались на форме входа?
 * Метку снимаем в любом случае — повтор допустим ровно один.
 */
export function consumeOAuthReturn(): boolean {
  try {
    const raw = sessionStorage.getItem(KEY);
    if (!raw) return false;
    sessionStorage.removeItem(KEY);
    const started = Number(raw);
    return Number.isFinite(started) && Date.now() - started < MAX_AGE_MS;
  } catch {
    return false;
  }
}
