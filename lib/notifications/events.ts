import type { NotificationSettings } from '@/lib/contracts/lk';

/**
 * Названия строк матрицы уведомлений и порядок их показа.
 *
 * ⚠️ Этот список **не задаёт** набор строк — их задаёт ответ сервера
 * (`GET /lk/notifications/settings`). Категория появляется в интерфейсе ровно
 * тогда, когда сервер начинает её отдавать и принимать: `PUT` молча выбрасывает
 * незнакомые ключи (`sanitizeMatrix`), поэтому нарисованный заранее
 * переключатель сбрасывался бы при перезагрузке страницы — худший вид
 * настройки, который делает вид, что работает.
 *
 * Неизвестный ключ рисуется как есть, а не прячется: лучше техническое
 * название, чем настройка, о существовании которой человек не знает.
 */
export const EVENT_META: Record<string, { label: string; hint: string; warn?: string }> = {
  billing: {
    label: 'Оплата и подписка',
    hint: 'Оплата получена, оплата не прошла, окончание подписки',
    /**
     * 🔴 Просьба сервера, и она по делу (F20 §10.1): блокировка по истечении
     * наступает **без grace-периода**, а предупреждения «осталось 7/3/1 день»
     * ходят по этой же категории. Выключивший её однажды обнаружит вставшие
     * интеграции без единого предупреждения — об этом надо сказать вслух,
     * а не делать скрытое исключение на сервере.
     */
    warn:
      'Сюда же приходят предупреждения об окончании подписки. Если выключить, ' +
      'мы не сможем предупредить, что доступ вот-вот приостановится, — ' +
      'обмен останавливается сразу по истечении оплаченного срока.',
  },
  integration_errors: { label: 'Ошибки интеграций', hint: 'Обмен не прошёл, сервис недоступен' },
  limit_exceeded: { label: 'Лимиты тарифа', hint: 'Приближение к лимиту и его исчерпание' },
  reports: { label: 'Отчёты', hint: 'Сводка за период' },
  news: { label: 'Новости продукта', hint: 'Новые механики и сервисы' },
};

const ORDER = Object.keys(EVENT_META);

export interface MatrixRow {
  key: string;
  label: string;
  hint: string;
  warn?: string;
}

/** Строки матрицы: те, что прислал сервер, в нашем порядке; незнакомые — в конец */
export function matrixRows(matrix: NotificationSettings['matrix']): MatrixRow[] {
  return Object.keys(matrix)
    .sort((a, b) => {
      const ia = ORDER.indexOf(a);
      const ib = ORDER.indexOf(b);
      return (ia === -1 ? ORDER.length : ia) - (ib === -1 ? ORDER.length : ib);
    })
    .map((key) => ({
      key,
      label: EVENT_META[key]?.label ?? key,
      hint: EVENT_META[key]?.hint ?? '',
      warn: EVENT_META[key]?.warn,
    }));
}
