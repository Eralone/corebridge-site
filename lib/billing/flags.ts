/**
 * Переключатели платёжного контура.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 * Сервер умеет принять деньги (F20 P0) и с этапом P1 закрыл всё, что делало
 * оплату опасной для клиента. Проверено в выложенных контейнерах 2026-08-06
 * (образ `sha-32730bf`, миграция `030_billing_notifications`):
 *
 *   · продление считается от конца оплаченного периода, а не от «сейчас»
 *     (`jwt-generator.js`, `extend_from_current` — P1-4);
 *   · зависшие платежи разбирает сверка через Robokassa OpStateExt раз
 *     в 15 минут (`payment-reconciler.js` — P1-3);
 *   · письма биллинга есть в базе: `payment_succeeded`, `payment_failed`,
 *     `subscription_expiring`, `subscription_expired` (P1-6).
 *
 * С этапом P3-2 (образ `sha-39357d6`, миграция `031_plan_change_proration`)
 * закрылась и смена тарифа: оплаченная стоимость сохраняется в обе стороны —
 * апгрейд оплачивается доплатой за оставшиеся дни, даунгрейд бесплатен
 * и отодвигает дату окончания.
 *
 * ⚠️ Что **не** закрыто и потому держит флаг выключенным:
 *
 *   · **живой тестовый платёж на 10 ₽ владельцем не проведён** — это последний
 *     пункт самого сервера, и снимает флаг он же;
 *   · фискализация выключена, вопрос чеков по 54-ФЗ у бухгалтера.
 *
 * Порядок включения: владелец проводит тестовый платёж → снимает флаг.
 *
 * ── Почему не NEXT_PUBLIC_* ─────────────────────────────────────────────────
 * `NEXT_PUBLIC_*` вшивается в бандл на сборке: чтобы включить оплату, пришлось
 * бы пересобирать сайт и помнить про переменную окружения именно в момент
 * сборки. Здесь значение читается на сервере при запросе и приезжает в клиентские
 * компоненты пропом — включение это правка юнита systemd и `systemctl restart`.
 * Страницы, которые их читают, помечены `dynamic = 'force-dynamic'`, иначе
 * Next вшил бы значение в статический пререндер на сборке.
 */

export interface BillingFlags {
  /** Кнопка «Оплатить» доступна клиентам */
  pay: boolean;
  /** Галочка автоплатежа видна. ⚠️ Подписки Robokassa всё ещё на модерации,
   *  планировщик списаний — этап P2. Тексты писем (`autopay_charged`,
   *  `autopay_failed`) уже в базе, но списывать нечем. Держать выключенной
   *  до отдельного сигнала сервера */
  autopay: boolean;
}

const on = (v: string | undefined) => v === 'true' || v === '1';

export function billingFlags(): BillingFlags {
  return {
    pay: on(process.env.BILLING_PAY_ENABLED),
    autopay: on(process.env.BILLING_AUTOPAY_ENABLED),
  };
}
