import type { Profile } from '@/lib/contracts/lk';

/**
 * Кто оплачивает: человек или компания.
 *
 * ── Почему это выводится, а не хранится ─────────────────────────────────────
 * Отдельного атрибута «физлицо / компания» у аккаунта нет ни на сервере, ни
 * здесь, и заводить его не понадобилось: **заполненный ИНН в настройках уже
 * и есть заявление «плачу от компании»**. Счёт без ИНН всё равно не выставить,
 * так что признак и условие тут совпадают.
 *
 * ⚠️ Главное свойство этой развязки: она ничего не **отбирает**. Карта и СБП
 * доступны всем — компании платят картой сплошь и рядом, и закрывать им
 * быстрый путь нельзя. Реквизиты влияют только на то, что предлагается
 * **дополнительно** (счёт по безналу) и какие документы за этим следуют.
 *
 * Отсюда же ответ на вопрос «а если человек оплатил как физлицо, а потом стал
 * компанией»: ничего не происходит. Тариф, оплаченный срок и лицензия
 * не зависят от реквизитов вовсе — их заполнение не событие, а справка.
 *
 * Признаком считаем именно ИНН, а не название: «ООО Ромашка» в поле имени
 * бухгалтерию не устроит, а ИНН — единственное, без чего счёт не выписать.
 */
export function isCompanyPayer(profile: Profile | null | undefined): boolean {
  return Boolean(profile?.company.company_inn?.trim());
}

/** Название для подписи счёта: компания, если названа, иначе просто «компанию» */
export function payerCompanyName(profile: Profile | null | undefined): string | null {
  const name = profile?.company.company_name?.trim();
  return name || null;
}
